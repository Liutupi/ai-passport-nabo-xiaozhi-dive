"""Generate the DIVE NABO sprite table for the firmware from Codex frames.

Reads ``manifest.json`` from the nabo-dive art repository (one skin), scales each 256 px frame with
the manifest's shared factor, and quantizes all frames together into one
64-entry palette whose entries carry colour, alpha and top rim-light strength.
Index 0 is transparent. Each frame's index bytes are raw-deflate compressed; the
firmware inflates one frame at a time with the ESP32-C3 ROM tinfl decoder.

The firmware applies depth tint and zone rim colour by rewriting the palette,
so no per-zone pixel data is stored.

Usage:
    python3 tools/generate_dive_sprites.py [--skin a] [--source ../nabo-dive]

The art lives in https://github.com/Liutupi/nabo-dive; clone it next to this repository.
"""

import argparse
import hashlib
import json
import logging
import zlib
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from PIL import Image
from scipy.cluster.vq import kmeans2

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT.parent / "nabo-dive"  # sibling checkout of the art repository
OUT = ROOT / "xiaozhi-esp32/main/boards/folotoy/ai-passport-nabo/nabo_dive_sprites.c"
RIM_REACH = 8          # source pixels above that must be clear for rim light
ALPHA_MIN = 8          # below this a pixel is transparent
PALETTE_SIZE = 64      # plus index 0 (transparent); 64 is visually lossless at 66 px
SEED = 7


def _scale(img: Image.Image, cell: int) -> np.ndarray:
    """Premultiplied Lanczos downscale; returns float RGBA in 0..1."""
    small = img.convert("RGBa").resize((cell, cell), Image.LANCZOS).convert("RGBA")
    return np.asarray(small, dtype=np.float32) / 255.0


def _rim(img: Image.Image, cell: int) -> np.ndarray:
    """Top-edge rim strength (0..1) at the target size."""
    alpha = np.asarray(img, dtype=np.float32)[..., 3] / 255.0
    rim = np.zeros_like(alpha)
    for k in range(1, RIM_REACH + 1):
        above = np.ones_like(alpha)
        above[k:] = alpha[:-k]
        rim = np.maximum(rim, (above < 0.25) * (1 - (k - 1) / RIM_REACH))
    rim *= alpha
    mask = Image.fromarray((rim * 255).astype(np.uint8), "L").resize((cell, cell), Image.LANCZOS)
    return np.asarray(mask, dtype=np.float32) / 255.0


def _deflate(data: bytes) -> bytes:
    """Raw deflate (no zlib header), as expected by tinfl without PARSE_ZLIB_HEADER."""
    comp = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    return comp.compress(data) + comp.flush()


def build(skin: str, dive: Path = DEFAULT_SOURCE) -> Tuple[str, Dict]:
    """Return the generated C source and a summary."""
    manifest = json.loads((dive / "manifest.json").read_text(encoding="utf-8"))
    if skin not in manifest["skins"]:
        raise ValueError(f"unknown skin {skin}")
    scale = float(manifest["preview_scale_to_actual"])
    cell = round(manifest["canvas"][0] * scale)
    anchor = [round(v * scale) for v in manifest["anchor"]]

    clips: List[Tuple[str, Dict]] = list(manifest["animations"].items())
    frames, rims = [], []
    for _, spec in clips:
        for rel in spec["skin_frames"][skin]:
            src = Image.open(dive / rel).convert("RGBA")
            frames.append(_scale(src, cell))
            rims.append(_rim(src, cell))
    stack = np.stack(frames)                      # F, H, W, 4 (premultiplied colour is unpremultiplied by PIL)
    rim = np.stack(rims)[..., None]
    opaque = stack[..., 3] * 255 >= ALPHA_MIN
    features = np.concatenate([stack[..., :3], stack[..., 3:4] * 1.5, rim * 0.8], axis=-1)[opaque]
    np.random.seed(SEED)
    centroids, labels = kmeans2(features.astype(np.float64), PALETTE_SIZE, minit="++", seed=SEED)
    index = np.zeros(stack.shape[:3], dtype=np.uint8)
    index[opaque] = labels.astype(np.uint8) + 1

    palette = [(0, 0, 0, 0, 0)]
    for c in centroids:
        r, g, b = (int(round(np.clip(v, 0, 1) * 255)) for v in c[:3])
        a = int(round(np.clip(c[3] / 1.5, 0, 1) * 255))
        rm = int(round(np.clip(c[4] / 0.8, 0, 1) * 255))
        palette.append((r, g, b, a, rm))

    blob, offsets = bytearray(), []
    for f in range(index.shape[0]):
        offsets.append(len(blob))
        blob += _deflate(index[f].tobytes())
    offsets.append(len(blob))

    lines = [
        "// Generated by tools/generate_dive_sprites.py from nabo-dive/manifest.json. Do not edit.",
        f"// Source revision {manifest.get('revision')}, skin {skin}.",
        '#include "nabo_dive_sprites.h"',
        "",
        f"const nabo_dive_rgba_t nabo_dive_palette[{len(palette)}] = {{",
    ]
    for i in range(0, len(palette), 4):
        lines.append("    " + " ".join(f"{{{r}, {g}, {b}, {a}, {m}}}," for r, g, b, a, m in palette[i:i + 4]))
    lines.append("};")
    lines.append(f"const uint32_t nabo_dive_frame_offsets[{len(offsets)}] = {{")
    for i in range(0, len(offsets), 10):
        lines.append("    " + ", ".join(str(v) for v in offsets[i:i + 10]) + ",")
    lines.append("};")
    lines.append(f"const uint8_t nabo_dive_pixels[{len(blob)}] = {{")
    for i in range(0, len(blob), 20):
        lines.append("    " + ", ".join(str(v) for v in blob[i:i + 20]) + ",")
    lines.append("};")
    lines.append(f"const nabo_dive_box_t nabo_dive_boxes[{index.shape[0]}] = {{")
    for f in range(index.shape[0]):
        ys, xs = np.nonzero(index[f])
        lines.append(f"    {{{xs.min()}, {ys.min()}, {xs.max() + 1}, {ys.max() + 1}}},")
    lines.append("};")
    lines.append("const nabo_dive_clip_t nabo_dive_clips[NABO_DIVE_CLIP_COUNT] = {")
    first = 0
    names = []
    for name, spec in clips:
        count = len(spec["skin_frames"][skin])
        events = spec.get("events") or {}
        event = int(next(iter(events.values()))) if events else -1
        lines.append(f"    {{{first}, {count}, {spec.get('fps', manifest['fps'])}, {1 if spec['loop'] else 0}, {event}}},  // {name}")
        names.append(name)
        first += count
    lines.append("};")
    source = "\n".join(lines) + "\n"
    summary = {"cell": cell, "anchor": anchor, "frames": int(index.shape[0]), "clips": names,
               "pixel_bytes": len(blob), "palette": len(palette),
               "total_bytes": len(blob) + len(offsets) * 4 + len(palette) * 5}
    return source, summary


def header(summary: Dict) -> str:
    """Generated header with sizes and clip ids."""
    ids = "\n".join(f"    NABO_DIVE_CLIP_{n.upper()}," for n in summary["clips"])
    return f"""// Generated by tools/generate_dive_sprites.py. Do not edit.
#pragma once
#include <stdint.h>

#define NABO_DIVE_CELL {summary['cell']}
#define NABO_DIVE_ANCHOR_X {summary['anchor'][0]}
#define NABO_DIVE_ANCHOR_Y {summary['anchor'][1]}
#define NABO_DIVE_FRAME_COUNT {summary['frames']}

typedef struct {{
    uint8_t r, g, b, a, rim;
}} nabo_dive_rgba_t;

typedef struct {{
    uint8_t u0, v0, u1, v1;  // opaque bounds within the cell, exclusive end
}} nabo_dive_box_t;

typedef struct {{
    uint8_t first, count, fps, loop;
    int8_t event_frame;  // e.g. the swallow frame of gulp, -1 if none
}} nabo_dive_clip_t;

enum {{
{ids}
    NABO_DIVE_CLIP_COUNT
}};

#define NABO_DIVE_PALETTE_SIZE {summary['palette']}

extern const nabo_dive_rgba_t nabo_dive_palette[NABO_DIVE_PALETTE_SIZE];
// Raw-deflate index bytes (CELL x CELL per frame); frame f is [offsets[f], offsets[f + 1]).
extern const uint32_t nabo_dive_frame_offsets[NABO_DIVE_FRAME_COUNT + 1];
extern const uint8_t nabo_dive_pixels[];
extern const nabo_dive_box_t nabo_dive_boxes[NABO_DIVE_FRAME_COUNT];
extern const nabo_dive_clip_t nabo_dive_clips[NABO_DIVE_CLIP_COUNT];
"""


def main() -> None:
    """Write nabo_dive_sprites.c/.h."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--skin", default="a")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="nabo-dive checkout")
    args = parser.parse_args()
    source, summary = build(args.skin, args.source.resolve())
    OUT.write_text(source, encoding="utf-8")
    OUT.with_suffix(".h").write_text(header(summary), encoding="utf-8")
    logger.info("%s", json.dumps(summary, ensure_ascii=False))
    logger.info("sha256 %s", hashlib.sha256(source.encode()).hexdigest()[:16])


if __name__ == "__main__":
    main()
